-- Cuentas de acceso de proveedores. Si la cuenta pertenece a un colaborador
-- (p.ej. responsable de la tarea que firma), empleado_proveedor_id lo liga.
-- Su actor_id en auditoría/firmas es 'P-' || id.
CREATE TABLE usuarios_proveedor (
  id                      serial PRIMARY KEY,
  proveedor_id            integer NOT NULL REFERENCES proveedores(id),
  empleado_proveedor_id   integer REFERENCES empleados_proveedor(id),
  nombre                  text NOT NULL,
  -- Usuario de acceso de 8 caracteres: 2 letras del nombre + 2 del apellido
  -- paterno + 2 del materno (minúsculas, sin acentos, relleno 'x') + 2 dígitos aleatorios.
  usuario                 text NOT NULL UNIQUE CHECK (usuario ~ '^[a-z]{6}[0-9]{2}$'),
  password_hash           text NOT NULL,              -- hash con sal (scrypt/argon2); nunca la contraseña
  debe_cambiar_password   boolean NOT NULL DEFAULT true, -- true tras alta o restablecimiento por admin
  intentos_fallidos       smallint NOT NULL DEFAULT 0,
  bloqueado_hasta         timestamptz,
  correo                  text,                       -- solo contacto (no hay envío de correos)
  es_administrador        boolean NOT NULL DEFAULT false,
  activo                  boolean NOT NULL DEFAULT true,
  creado_en               timestamptz NOT NULL DEFAULT now(),
  creado_por              text,
  actualizado_en          timestamptz NOT NULL DEFAULT now(),
  actualizado_por         text
);
CREATE INDEX idx_usuarios_proveedor_proveedor ON usuarios_proveedor(proveedor_id);

-- Catálogo de documentos requeridos.
--  * obligatorio = true: lo exige a todo el personal / equipo.
--  * tipo_trabajo_codigo NOT NULL: DC-3 del trabajo; se exige solo si el
--    colaborador declaró ese trabajo (empleado_proveedor_trabajos).
--  * vigencia_meses: caducidad contada desde fecha_emision (examen médico 12,
--    inducción 24). Si la versión trae fecha_vencimiento, gana la más próxima.
--  * permiso_revision: permiso que debe tener quien revisa (médico != HSEA).
CREATE TABLE tipos_documento (
  codigo                  text PRIMARY KEY,
  nombre                  text NOT NULL,
  aplica_a                text NOT NULL CHECK (aplica_a IN ('EMPLEADO', 'EQUIPO', 'PROVEEDOR')),
  categoria               text NOT NULL CHECK (categoria IN ('IMSS', 'MEDICO', 'CAPACITACION', 'EPP', 'CERTIFICACION')),
  obligatorio             boolean NOT NULL DEFAULT true,
  vigencia_meses          integer CHECK (vigencia_meses IS NULL OR vigencia_meses > 0),
  tipo_trabajo_codigo     text REFERENCES tipos_trabajo(codigo),
  permiso_revision        text NOT NULL REFERENCES permisos(codigo),
  activo                  boolean NOT NULL DEFAULT true,
  CHECK (tipo_trabajo_codigo IS NULL OR (aplica_a = 'EMPLEADO' AND NOT obligatorio))
);

-- Un "expediente" por sujeto y tipo de documento; las versiones cuelgan de él.
CREATE TABLE documentos_contratista (
  id                      bigserial PRIMARY KEY,
  empleado_proveedor_id   integer REFERENCES empleados_proveedor(id),
  equipo_proveedor_id     integer REFERENCES equipos_proveedor(id),
  proveedor_id            integer REFERENCES proveedores(id),   -- documentos de la empresa (persona moral)
  tipo_documento_codigo   text NOT NULL REFERENCES tipos_documento(codigo),
  creado_en               timestamptz NOT NULL DEFAULT now(),
  creado_por              text NOT NULL,
  CONSTRAINT documentos_contratista_un_dueno
    CHECK (num_nonnulls(empleado_proveedor_id, equipo_proveedor_id, proveedor_id) = 1)
);
CREATE UNIQUE INDEX uq_documento_proveedor
  ON documentos_contratista(proveedor_id, tipo_documento_codigo) WHERE proveedor_id IS NOT NULL;
CREATE UNIQUE INDEX uq_documento_empleado
  ON documentos_contratista(empleado_proveedor_id, tipo_documento_codigo) WHERE empleado_proveedor_id IS NOT NULL;
CREATE UNIQUE INDEX uq_documento_equipo
  ON documentos_contratista(equipo_proveedor_id, tipo_documento_codigo) WHERE equipo_proveedor_id IS NOT NULL;

-- El tipo de documento debe corresponder al tipo de sujeto (empleado / equipo).
CREATE FUNCTION validar_documento_contratista() RETURNS trigger AS $$
DECLARE
  v_aplica_a text;
BEGIN
  SELECT aplica_a INTO v_aplica_a FROM tipos_documento WHERE codigo = NEW.tipo_documento_codigo;
  IF (v_aplica_a = 'EMPLEADO' AND NEW.empleado_proveedor_id IS NULL)
     OR (v_aplica_a = 'EQUIPO' AND NEW.equipo_proveedor_id IS NULL)
     OR (v_aplica_a = 'PROVEEDOR' AND NEW.proveedor_id IS NULL) THEN
    RAISE EXCEPTION 'El documento % no aplica a este tipo de sujeto', NEW.tipo_documento_codigo;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_documento_contratista_valido
  BEFORE INSERT ON documentos_contratista
  FOR EACH ROW EXECUTE FUNCTION validar_documento_contratista();

-- Versiones inmutables: una resubida crea numero_version + 1; las anteriores se conservan.
CREATE TABLE versiones_documento (
  id                      bigserial PRIMARY KEY,
  documento_id            bigint NOT NULL REFERENCES documentos_contratista(id),
  numero_version          integer NOT NULL CHECK (numero_version > 0),
  nombre_archivo          text NOT NULL,
  tipo_mime               text NOT NULL,
  tamano_bytes            bigint NOT NULL CHECK (tamano_bytes > 0),
  -- Política de privacidad: el archivo (con datos personales) solo sirve para
  -- validar; 15 días después de aprobado se elimina del almacenamiento y esta
  -- ruta pasa a NULL. Se conservan sha256, fechas y la revisión (trazabilidad).
  ruta_almacenamiento     text,
  archivo_eliminado_en    timestamptz,
  archivo_eliminado_por   text,                       -- 'SISTEMA' en la purga automática
  sha256                  text NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
  fecha_emision           date,
  fecha_vencimiento       date,
  subido_por              text NOT NULL,
  subido_en               timestamptz NOT NULL DEFAULT now(),
  UNIQUE (documento_id, numero_version),
  CHECK (fecha_vencimiento IS NULL OR fecha_emision IS NULL OR fecha_vencimiento >= fecha_emision),
  CHECK ((ruta_almacenamiento IS NULL) = (archivo_eliminado_en IS NOT NULL))
);

-- Única modificación permitida sobre una versión: la purga de su archivo.
CREATE FUNCTION permitir_solo_purga_archivo() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE'
     OR OLD.archivo_eliminado_en IS NOT NULL
     OR NEW.archivo_eliminado_en IS NULL
     OR (to_jsonb(NEW) - 'ruta_almacenamiento' - 'archivo_eliminado_en' - 'archivo_eliminado_por')
        <> (to_jsonb(OLD) - 'ruta_almacenamiento' - 'archivo_eliminado_en' - 'archivo_eliminado_por') THEN
    RAISE EXCEPTION 'versiones_documento es de solo anexar: solo se permite purgar el archivo';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Revisión de una versión (una sola; si se rechaza, el proveedor sube otra versión).
CREATE TABLE revisiones_documento (
