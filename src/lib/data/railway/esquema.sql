  estatus                   text NOT NULL DEFAULT 'draft'
                            CHECK (estatus IN ('draft', 'submitted', 'approved', 'rejected', 'closed')),
  solicitante_tipo          text NOT NULL CHECK (solicitante_tipo IN ('EMPLEADO', 'USUARIO_PROVEEDOR')),
  solicitante_no_empleado   integer REFERENCES empleados(no_empleado),
  solicitante_usuario_proveedor_id integer REFERENCES usuarios_proveedor(id),
  proveedor_id              integer REFERENCES proveedores(id),  -- si lo ejecuta un contratista
  -- Área del permiso (alcance de las firmas): los seis formatos la piden con un selector.
  departamento_id           integer NOT NULL REFERENCES departamentos(id),
  subdepartamento_id        integer,
  campos                    jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- Solo los pasos que NO son un rol de firma (solicitante, verificaciones, revalidación, participantes
  -- del JSA): clave, firmante, fecha y trazo. Las firmas de rol viven únicamente en firmas_permiso.
