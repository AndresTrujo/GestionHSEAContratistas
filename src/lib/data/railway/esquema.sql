-- Cursos que un rol exige tener aprobados (opcional; hoy sin uso).
CREATE TABLE rol_cursos_requeridos (
  rol_id              integer NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
  id_curso            text NOT NULL REFERENCES cursos(id_curso),
  creado_en           timestamptz NOT NULL DEFAULT now(),
  creado_por          integer,
  PRIMARY KEY (rol_id, id_curso)
);

-- Asignación de un rol a un empleado, con alcance y vigencia.
-- alcance GLOBAL: toda la organización. LINEA_MANDO / DEPARTAMENTO /
-- SUBDEPARTAMENTO: el rol aplica a esa área y a todo lo que cuelga de ella.
-- Se revoca (revocado_en/por), nunca se borra. Varios empleados pueden
-- tener el mismo rol en la misma área.
CREATE TABLE empleado_roles (
  id                  bigserial PRIMARY KEY,
  no_empleado         integer NOT NULL REFERENCES empleados(no_empleado),
  rol_id              integer NOT NULL REFERENCES roles(id),
  alcance             text NOT NULL DEFAULT 'GLOBAL'
                      CHECK (alcance IN ('GLOBAL', 'LINEA_MANDO', 'DEPARTAMENTO', 'SUBDEPARTAMENTO')),
  linea_mando_id      integer REFERENCES lineas_mando(id),
  departamento_id     integer REFERENCES departamentos(id),
  subdepartamento_id  integer REFERENCES subdepartamentos(id),
  vigente_desde       date NOT NULL DEFAULT hoy_mx(),
  vigente_hasta       date,
  otorgado_por        integer NOT NULL REFERENCES empleados(no_empleado),
  motivo              text,
  revocado_en         timestamptz,
  revocado_por        integer REFERENCES empleados(no_empleado),
  creado_en           timestamptz NOT NULL DEFAULT now(),
  creado_por          integer,
  actualizado_en      timestamptz NOT NULL DEFAULT now(),
  actualizado_por     integer,
  CHECK ((alcance = 'GLOBAL'          AND num_nonnulls(linea_mando_id, departamento_id, subdepartamento_id) = 0)
      OR (alcance = 'LINEA_MANDO'     AND linea_mando_id IS NOT NULL     AND num_nonnulls(departamento_id, subdepartamento_id) = 0)
      OR (alcance = 'DEPARTAMENTO'    AND departamento_id IS NOT NULL    AND num_nonnulls(linea_mando_id, subdepartamento_id) = 0)
      OR (alcance = 'SUBDEPARTAMENTO' AND subdepartamento_id IS NOT NULL AND num_nonnulls(linea_mando_id, departamento_id) = 0)),
  CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde),
  CHECK ((revocado_en IS NULL) = (revocado_por IS NULL))
);
CREATE INDEX idx_empleado_roles_empleado ON empleado_roles(no_empleado) WHERE revocado_en IS NULL;
CREATE INDEX idx_empleado_roles_rol ON empleado_roles(rol_id) WHERE revocado_en IS NULL;

