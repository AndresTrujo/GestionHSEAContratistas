-- ---------------------------------------------------------------------
-- 2. CARGOS DE ÁREA: GERENTES y ENCARGADOS (con vigencia histórica)
--    Reemplaza las columnas NoEmpleadoResponsable del Excel.
--    GERENTE   -> responsable de una línea de mando
--    ENCARGADO -> responsable de un departamento o subdepartamento
--    Pueden existir varios encargados vigentes por área; por diseño NO hay
--    restricción de unicidad por área ni figura de suplente (todos son titulares).
-- ---------------------------------------------------------------------

CREATE TABLE cargos_area (
  id                  bigserial PRIMARY KEY,
  no_empleado         integer NOT NULL REFERENCES empleados(no_empleado),
  cargo               text NOT NULL CHECK (cargo IN ('GERENTE', 'ENCARGADO')),
  linea_mando_id      integer REFERENCES lineas_mando(id),
  departamento_id     integer REFERENCES departamentos(id),
  subdepartamento_id  integer REFERENCES subdepartamentos(id),
  vigente_desde       date NOT NULL DEFAULT hoy_mx(),
  vigente_hasta       date,
  motivo              text,
  creado_en           timestamptz NOT NULL DEFAULT now(),
  creado_por          integer,
  actualizado_en      timestamptz NOT NULL DEFAULT now(),
  actualizado_por     integer,
  -- exactamente un nivel de alcance
  CHECK (num_nonnulls(linea_mando_id, departamento_id, subdepartamento_id) = 1),
  -- GERENTE solo a nivel línea; ENCARGADO a departamento o subdepartamento
  CHECK ((cargo = 'GERENTE'   AND linea_mando_id IS NOT NULL)
      OR (cargo = 'ENCARGADO' AND linea_mando_id IS NULL)),
  CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde)
);
CREATE INDEX idx_cargos_area_empleado ON cargos_area(no_empleado);
CREATE INDEX idx_cargos_area_vigentes ON cargos_area(cargo) WHERE vigente_hasta IS NULL;

