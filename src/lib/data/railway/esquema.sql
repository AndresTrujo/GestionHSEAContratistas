-- ---------------------------------------------------------------------
-- 7. BITÁCORA DE INGRESOS A PLANTA (personal de proveedores)
--    Cada ingreso registra la verificación de EPP completo y el semáforo
--    real en ese momento (lo fija un trigger a partir de la vista; un
--    ingreso PERMITIDO solo es válido en VERDE y con EPP completo).
--    Es histórica: la única modificación permitida es registrar la salida.
-- ---------------------------------------------------------------------

CREATE TABLE registros_ingreso (
  id                        bigserial PRIMARY KEY,
  empleado_proveedor_id     integer NOT NULL REFERENCES empleados_proveedor(id),
  ingreso_en                timestamptz NOT NULL DEFAULT now(),
  resultado                 text NOT NULL CHECK (resultado IN ('PERMITIDO', 'DENEGADO')),
  semaforo_al_ingresar      text NOT NULL DEFAULT 'ROJO' CHECK (semaforo_al_ingresar IN ('ROJO', 'AMARILLO', 'VERDE')),
  epp_completo              boolean NOT NULL,
  observaciones             text,
  motivo_denegacion         text,
  permiso_id                text REFERENCES permisos_trabajo(id),
  registrado_por            integer NOT NULL REFERENCES empleados(no_empleado),
  salida_en                 timestamptz,
  salida_registrada_por     integer REFERENCES empleados(no_empleado),
  CHECK (resultado = 'DENEGADO' OR (semaforo_al_ingresar = 'VERDE' AND epp_completo)),
  CHECK (resultado = 'PERMITIDO' OR motivo_denegacion IS NOT NULL),
  CHECK (salida_en IS NULL OR (resultado = 'PERMITIDO' AND salida_en >= ingreso_en)),
  CHECK ((salida_en IS NULL) = (salida_registrada_por IS NULL))
);
CREATE INDEX idx_ingresos_empleado ON registros_ingreso(empleado_proveedor_id, ingreso_en DESC);
-- un colaborador no puede tener dos ingresos abiertos a la vez (también ante concurrencia)
CREATE UNIQUE INDEX uq_ingreso_abierto ON registros_ingreso(empleado_proveedor_id) WHERE salida_en IS NULL AND resultado = 'PERMITIDO';

-- El semáforo se toma de la vista, no de lo que mande el cliente.
CREATE FUNCTION fijar_semaforo_ingreso() RETURNS trigger AS $$
BEGIN
  NEW.semaforo_al_ingresar := COALESCE(
    (SELECT semaforo FROM v_semaforo_empleado_proveedor
      WHERE empleado_proveedor_id = NEW.empleado_proveedor_id), 'ROJO');
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Única modificación permitida: registrar la salida, una sola vez.
CREATE FUNCTION permitir_solo_salida() RETURNS trigger AS $$
BEGIN
  IF OLD.salida_en IS NOT NULL OR NEW.salida_en IS NULL
     OR (to_jsonb(NEW) - 'salida_en' - 'salida_registrada_por')
        <> (to_jsonb(OLD) - 'salida_en' - 'salida_registrada_por') THEN
    RAISE EXCEPTION 'registros_ingreso es histórico: solo se permite registrar la salida una vez';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_ingreso_semaforo
  BEFORE INSERT ON registros_ingreso
  FOR EACH ROW EXECUTE FUNCTION fijar_semaforo_ingreso();
CREATE TRIGGER trg_ingreso_solo_salida
  BEFORE UPDATE ON registros_ingreso
  FOR EACH ROW EXECUTE FUNCTION permitir_solo_salida();
CREATE TRIGGER trg_ingreso_sin_borrado
  BEFORE DELETE ON registros_ingreso
  FOR EACH ROW EXECUTE FUNCTION bloquear_borrado();

