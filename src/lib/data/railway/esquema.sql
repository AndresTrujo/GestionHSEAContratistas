CREATE TABLE credenciales_firma (
  id                      bigserial PRIMARY KEY,
  firmante_tipo           text NOT NULL CHECK (firmante_tipo IN ('EMPLEADO', 'USUARIO_PROVEEDOR')),
  no_empleado             integer REFERENCES empleados(no_empleado),
  usuario_proveedor_id    integer REFERENCES usuarios_proveedor(id),
  pin_hash                text NOT NULL,
  -- El PIN solo lo activa un administrador (sin correo): evita que un tercero
