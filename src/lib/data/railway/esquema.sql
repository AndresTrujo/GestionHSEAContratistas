  CHECK ((solicitante_tipo = 'EMPLEADO'          AND solicitante_no_empleado IS NOT NULL AND solicitante_usuario_proveedor_id IS NULL)
      OR (solicitante_tipo = 'USUARIO_PROVEEDOR' AND solicitante_usuario_proveedor_id IS NOT NULL AND solicitante_no_empleado IS NULL))
