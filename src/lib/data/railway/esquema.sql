CREATE UNIQUE INDEX uq_credencial_activa_proveedor
  ON credenciales_firma(usuario_proveedor_id) WHERE usuario_proveedor_id IS NOT NULL AND estado <> 'REVOCADA';

CREATE TABLE firmas_permiso (
  id                      bigserial PRIMARY KEY,
  permiso_id              text NOT NULL REFERENCES permisos_trabajo(id),
  rol_firma               text NOT NULL REFERENCES roles_firma(codigo),
  -- Firmante: empleado TFS o usuario de proveedor (sin número de empleado).
  firmante_tipo           text NOT NULL CHECK (firmante_tipo IN ('EMPLEADO', 'USUARIO_PROVEEDOR')),
  no_empleado             integer REFERENCES empleados(no_empleado),
  usuario_proveedor_id    integer REFERENCES usuarios_proveedor(id),
  -- área del permiso al firmar (alcance contra el que se validó)
  linea_mando_id          integer REFERENCES lineas_mando(id),
  departamento_id         integer REFERENCES departamentos(id),
