-- Consecutivo por tipo y año; se reinicia solo al cambiar el año (hoy_mx()).
CREATE TABLE contadores_folio (
  tipo_permiso_slug   text NOT NULL,
  anio                smallint NOT NULL,
  ultimo              integer NOT NULL,
  PRIMARY KEY (tipo_permiso_slug, anio)
);

-- Atómico y sin huecos por concurrencia: el bloqueo de fila serializa a quienes piden folio.
-- La app arma el texto (p.ej. 'TC-2026-0001') con su prefijo y estos dos números.
CREATE FUNCTION siguiente_consecutivo(p_tipo_permiso_slug text)
RETURNS TABLE (anio_folio smallint, consecutivo_folio integer) AS $$
  INSERT INTO contadores_folio (tipo_permiso_slug, anio, ultimo)
  VALUES (p_tipo_permiso_slug, EXTRACT(YEAR FROM hoy_mx())::smallint, 1)
  ON CONFLICT (tipo_permiso_slug, anio)
  DO UPDATE SET ultimo = contadores_folio.ultimo + 1
  RETURNING anio, ultimo;
$$ LANGUAGE sql;

CREATE TABLE permisos_trabajo (
  id                        text PRIMARY KEY,
  tipo_permiso_slug         text NOT NULL,
  anio                      smallint NOT NULL,
  consecutivo               integer NOT NULL,
