  actualizado_por     integer
);
CREATE INDEX idx_departamentos_linea ON departamentos(linea_mando_id);

-- Solo subdepartamentos reales. El Excel trae un "Sin subdepartamento"
-- por cada departamento: aquí eso se representa con subdepartamento_id NULL.
CREATE TABLE subdepartamentos (
  id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  departamento_id     integer NOT NULL REFERENCES departamentos(id),
  nombre              text NOT NULL,
  activo              boolean NOT NULL DEFAULT true,
  creado_en           timestamptz NOT NULL DEFAULT now(),
  creado_por          integer,
  actualizado_en      timestamptz NOT NULL DEFAULT now(),
  actualizado_por     integer,
  UNIQUE (departamento_id, nombre),
  UNIQUE (id, departamento_id)                          -- para FK compuesta desde permisos_trabajo
);

CREATE TABLE empleados (
  no_empleado             integer PRIMARY KEY,           -- identidad usada en login y auditoría
  primer_nombre           text NOT NULL,
  segundo_nombre          text,
  apellido_paterno        text NOT NULL,
  apellido_materno        text,
  genero                  text CHECK (genero IN ('MASCULINO', 'FEMENINO')),
  fecha_ingreso           date NOT NULL,
  fecha_baja              date,
  activo                  boolean NOT NULL DEFAULT true,
  puesto                  text NOT NULL,
  linea_mando_id          integer NOT NULL REFERENCES lineas_mando(id),
  departamento_id         integer NOT NULL REFERENCES departamentos(id),
  subdepartamento_id      integer REFERENCES subdepartamentos(id),
  jefe_no_empleado        integer REFERENCES empleados(no_empleado),
  creado_en               timestamptz NOT NULL DEFAULT now(),
  creado_por              integer,
  actualizado_en          timestamptz NOT NULL DEFAULT now(),
  actualizado_por         integer,
  -- con fecha_baja => inactivo. (El Excel trae 14 inactivos sin fecha_baja, p.ej. residentes.)
  CHECK (fecha_baja IS NULL OR NOT activo),
  CHECK (jefe_no_empleado IS NULL OR jefe_no_empleado <> no_empleado)
