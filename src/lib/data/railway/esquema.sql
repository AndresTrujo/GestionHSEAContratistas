CREATE INDEX idx_empleados_departamento ON empleados(departamento_id);
CREATE INDEX idx_empleados_subdepartamento ON empleados(subdepartamento_id);
CREATE INDEX idx_empleados_jefe ON empleados(jefe_no_empleado);
CREATE INDEX idx_empleados_activo ON empleados(activo);

-- El departamento debe pertenecer a la línea de mando indicada
-- y el subdepartamento al departamento indicado.
CREATE FUNCTION validar_estructura_empleado() RETURNS trigger AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM departamentos d
                 WHERE d.id = NEW.departamento_id AND d.linea_mando_id = NEW.linea_mando_id) THEN
    RAISE EXCEPTION 'El departamento % no pertenece a la línea de mando %',
      NEW.departamento_id, NEW.linea_mando_id;
  END IF;
  IF NEW.subdepartamento_id IS NOT NULL AND NOT EXISTS (
       SELECT 1 FROM subdepartamentos s
       WHERE s.id = NEW.subdepartamento_id AND s.departamento_id = NEW.departamento_id) THEN
    RAISE EXCEPTION 'El subdepartamento % no pertenece al departamento %',
      NEW.subdepartamento_id, NEW.departamento_id;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_empleados_estructura
  BEFORE INSERT OR UPDATE OF linea_mando_id, departamento_id, subdepartamento_id ON empleados
  FOR EACH ROW EXECUTE FUNCTION validar_estructura_empleado();

