-- Cada área (nivel más fino) con sus ancestros, para resolver alcances.
CREATE VIEW v_areas AS
  SELECT s.id AS subdepartamento_id, d.id AS departamento_id, d.linea_mando_id
    FROM subdepartamentos s JOIN departamentos d ON d.id = s.departamento_id
  UNION ALL
  SELECT NULL, d.id, d.linea_mando_id FROM departamentos d;

-- Roles vigentes de empleados ACTIVOS (revocados o vencidos excluidos).
CREATE VIEW v_roles_vigentes AS
  SELECT er.*, r.codigo AS rol_codigo
    FROM empleado_roles er
    JOIN roles r     ON r.id = er.rol_id AND r.activo
    JOIN empleados e ON e.no_empleado = er.no_empleado AND e.activo
   WHERE er.revocado_en IS NULL
     AND er.vigente_desde <= hoy_mx()
     AND (er.vigente_hasta IS NULL OR er.vigente_hasta >= hoy_mx());

-- Permisos efectivos por empleado y alcance (un renglón por permiso+asignación).
CREATE VIEW v_permisos_empleado AS
  SELECT v.no_empleado, rp.permiso_codigo, v.rol_codigo, v.id AS empleado_rol_id,
         v.alcance, v.linea_mando_id, v.departamento_id, v.subdepartamento_id
    FROM v_roles_vigentes v
    JOIN rol_permisos rp ON rp.rol_id = v.rol_id;

-- Cargos de área vigentes de empleados activos.
CREATE VIEW v_cargos_vigentes AS
  SELECT c.*
    FROM cargos_area c
    JOIN empleados e ON e.no_empleado = c.no_empleado AND e.activo
   WHERE c.vigente_desde <= hoy_mx()
     AND (c.vigente_hasta IS NULL OR c.vigente_hasta >= hoy_mx());

-- ¿Puede el empleado ejercer el permiso en el área dada?
-- p_subdepartamento_id puede ser NULL (área = departamento completo).
-- Un alcance cubre el área si es GLOBAL o si coincide con ella o con un ancestro.
CREATE FUNCTION tiene_permiso(
  p_no_empleado       integer,
  p_permiso           text,
  p_departamento_id   integer,
  p_subdepartamento_id integer DEFAULT NULL
) RETURNS boolean AS $$
  SELECT EXISTS (
    SELECT 1
      FROM v_permisos_empleado pe
      JOIN departamentos d ON d.id = p_departamento_id
     WHERE pe.no_empleado = p_no_empleado
       AND pe.permiso_codigo = p_permiso
       AND (pe.alcance = 'GLOBAL'
         OR (pe.alcance = 'LINEA_MANDO'     AND pe.linea_mando_id = d.linea_mando_id)
         OR (pe.alcance = 'DEPARTAMENTO'    AND pe.departamento_id = p_departamento_id)
         OR (pe.alcance = 'SUBDEPARTAMENTO' AND pe.subdepartamento_id = p_subdepartamento_id))
  );
$$ LANGUAGE sql STABLE;

-- ¿Cumple el empleado los cursos que el rol exige? (aprobado y, si el curso
-- tiene vigencia_meses, dentro de vigencia). Sin cursos requeridos => true.
CREATE FUNCTION cumple_cursos_rol(p_no_empleado integer, p_rol_id integer) RETURNS boolean AS $$
  SELECT NOT EXISTS (
    SELECT 1
      FROM rol_cursos_requeridos rc
      JOIN cursos c ON c.id_curso = rc.id_curso
     WHERE rc.rol_id = p_rol_id
       AND NOT EXISTS (
         SELECT 1
           FROM capacitaciones k
           JOIN estados_capacitacion es ON es.id = k.estado_id AND es.cuenta_como_aprobada
          WHERE k.no_empleado = p_no_empleado
            AND k.id_curso = rc.id_curso
            AND (c.vigencia_meses IS NULL
                 OR k.fecha >= (hoy_mx() - make_interval(months => c.vigencia_meses))::date)
       )
  );
$$ LANGUAGE sql STABLE;

-- Estado vigente de cada documento (última versión + su revisión):
--   EN_REVISION | APROBADO | RECHAZADO | REVOCADO | VENCIDO
-- vigente_hasta = la más próxima entre fecha_vencimiento de la versión y
-- fecha_emision + vigencia_meses del tipo (sin fecha_emision, la de subida).
CREATE VIEW v_documentos_estado AS
  SELECT d.id AS documento_id, d.empleado_proveedor_id, d.equipo_proveedor_id,
         d.tipo_documento_codigo, v.id AS version_id, v.numero_version,
         r.resultado AS resultado_revision, vig.vigente_hasta,
         CASE WHEN rv.revision_id IS NOT NULL             THEN 'REVOCADO'
              WHEN r.resultado = 'RECHAZADO'              THEN 'RECHAZADO'
              WHEN vig.vigente_hasta < hoy_mx()            THEN 'VENCIDO'
              WHEN r.resultado = 'APROBADO'                THEN 'APROBADO'
              ELSE 'EN_REVISION' END AS estado,
         d.proveedor_id
    FROM documentos_contratista d
    JOIN tipos_documento td ON td.codigo = d.tipo_documento_codigo
    JOIN LATERAL (SELECT * FROM versiones_documento x
                   WHERE x.documento_id = d.id
                   ORDER BY x.numero_version DESC LIMIT 1) v ON true
    LEFT JOIN revisiones_documento r ON r.version_id = v.id
    LEFT JOIN revocaciones_revision rv ON rv.revision_id = r.id
    CROSS JOIN LATERAL (
      SELECT LEAST(v.fecha_vencimiento,
                   (COALESCE(v.fecha_emision, (v.subido_en AT TIME ZONE 'America/Mexico_City')::date)
                      + make_interval(months => td.vigencia_meses))::date) AS vigente_hasta
    ) vig;

-- Requisitos de cada colaborador activo: los obligatorios + el DC-3 de cada
-- trabajo específico declarado. Sin documento => FALTANTE.
CREATE VIEW v_requisitos_empleado_proveedor AS
  SELECT ep.id AS empleado_proveedor_id, td.codigo AS tipo_documento_codigo,
         COALESCE(de.estado, 'FALTANTE') AS estado, de.vigente_hasta
    FROM empleados_proveedor ep
    JOIN tipos_documento td
      ON td.aplica_a IN ('EMPLEADO', 'PROVEEDOR') AND td.activo
     AND (td.obligatorio
          OR EXISTS (SELECT 1 FROM empleado_proveedor_trabajos t
                      WHERE t.empleado_proveedor_id = ep.id
                        AND t.retirado_en IS NULL
                        AND t.tipo_trabajo_codigo = td.tipo_trabajo_codigo))
    LEFT JOIN v_documentos_estado de
      ON de.tipo_documento_codigo = td.codigo
     AND ((td.aplica_a = 'EMPLEADO'  AND de.empleado_proveedor_id = ep.id)
          OR (td.aplica_a = 'PROVEEDOR' AND de.proveedor_id = ep.proveedor_id))
   WHERE ep.activo;

-- Semáforo del personal contratista:
--   ROJO     falta, está rechazado o venció algún requisito (o proveedor no ACTIVO)
--   AMARILLO todo cargado, pendiente de revisión / validación médica
--   VERDE    todo aprobado y vigente => puede entrar a planta
CREATE VIEW v_semaforo_empleado_proveedor AS
  SELECT ep.id AS empleado_proveedor_id, ep.proveedor_id,
         CASE WHEN p.estatus <> 'ACTIVO'
                OR bool_or(rq.estado IN ('FALTANTE', 'RECHAZADO', 'REVOCADO', 'VENCIDO')) THEN 'ROJO'
              WHEN bool_and(rq.estado = 'APROBADO')                             THEN 'VERDE'
              ELSE 'AMARILLO' END AS semaforo
    FROM empleados_proveedor ep
    JOIN proveedores p ON p.id = ep.proveedor_id
    JOIN v_requisitos_empleado_proveedor rq ON rq.empleado_proveedor_id = ep.id
   GROUP BY ep.id, ep.proveedor_id, p.estatus;

-- Mismo criterio para equipos (grúas, etc.): certificación obligatoria.
CREATE VIEW v_semaforo_equipo_proveedor AS
  SELECT e.id AS equipo_proveedor_id, e.proveedor_id,
         CASE WHEN p.estatus <> 'ACTIVO'
                OR bool_or(COALESCE(de.estado, 'FALTANTE') IN ('FALTANTE', 'RECHAZADO', 'REVOCADO', 'VENCIDO')) THEN 'ROJO'
              WHEN bool_and(de.estado = 'APROBADO')                                                  THEN 'VERDE'
              ELSE 'AMARILLO' END AS semaforo
    FROM equipos_proveedor e
    JOIN proveedores p ON p.id = e.proveedor_id
    JOIN tipos_documento td ON td.aplica_a = 'EQUIPO' AND td.activo AND td.obligatorio
    LEFT JOIN v_documentos_estado de
      ON de.equipo_proveedor_id = e.id AND de.tipo_documento_codigo = td.codigo
   WHERE e.activo
   GROUP BY e.id, e.proveedor_id, p.estatus;

-- Archivos que ya cumplieron 15 días desde su aprobación y deben eliminarse del
-- almacenamiento. Flujo del job: borrar el archivo -> UPDATE versiones_documento
-- (ruta NULL, archivo_eliminado_en/por) -> evento 'purgar_archivo' en auditoría.
CREATE VIEW v_archivos_por_purgar AS
  SELECT v.id AS version_id, v.documento_id, v.ruta_almacenamiento, r.revisado_en
    FROM versiones_documento v
    JOIN revisiones_documento r ON r.version_id = v.id AND r.resultado = 'APROBADO'
   WHERE v.archivo_eliminado_en IS NULL
     AND r.revisado_en <= now() - interval '15 days';

