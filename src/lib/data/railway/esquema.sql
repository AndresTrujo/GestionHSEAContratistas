  activada_por            integer NOT NULL REFERENCES empleados(no_empleado),
  estado                  text NOT NULL DEFAULT 'ACTIVA' CHECK (estado IN ('ACTIVA', 'BLOQUEADA', 'REVOCADA')),
  intentos_fallidos       smallint NOT NULL DEFAULT 0,
  bloqueada_hasta         timestamptz,
  creado_en               timestamptz NOT NULL DEFAULT now(),
  revocada_en             timestamptz,
  revocada_por            text,
  CHECK ((firmante_tipo = 'EMPLEADO'          AND no_empleado IS NOT NULL AND usuario_proveedor_id IS NULL)
      OR (firmante_tipo = 'USUARIO_PROVEEDOR' AND usuario_proveedor_id IS NOT NULL AND no_empleado IS NULL))
);
CREATE UNIQUE INDEX uq_credencial_activa_empleado
