-- =====================================================================
-- Plataforma de gestión digital HSEA — Esquema PostgreSQL (Railway)
-- Módulos: organización (líneas de mando, departamentos, empleados),
--          cargos de área (gerentes / encargados), roles y permisos,
--          capacitaciones, contratistas (proveedores, personal, equipos,
--          documentos con semáforo), firmas de permisos y auditoría.
-- Origen de la estructura de organización: Capacitacion_Master_v5.xlsx
-- Convención: tablas y columnas en español snake_case.
--
-- Identidad del actor (auditoría, firmas, columnas *_por de contratistas):
--   * Empleado TFS        -> no_empleado como texto, p.ej. '204692'
--   * Usuario de proveedor-> 'P-' + usuarios_proveedor.id, p.ej. 'P-17'
--   El prefijo evita colisiones entre ambos espacios de numeración.
--   Las tablas de organización/roles solo las modifican empleados, por eso
--   conservan creado_por/actualizado_por como integer (no_empleado).
--
-- Trazabilidad: toda mutación debe registrar un evento en
--   eventos_auditoria (append-only) dentro de la misma transacción.
-- Zona horaria: toda fecha "de hoy" usa hoy_mx() (America/Mexico_City),
--   nunca current_date (que depende de la zona del servidor).
-- =====================================================================

BEGIN;

CREATE FUNCTION hoy_mx() RETURNS date AS $$
  SELECT (now() AT TIME ZONE 'America/Mexico_City')::date;
$$ LANGUAGE sql STABLE;

CREATE FUNCTION bloquear_modificacion() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION '% es de solo anexar: no se permite %', TG_TABLE_NAME, TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE FUNCTION bloquear_borrado() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION '% no admite borrado: dar de baja o revocar en su lugar', TG_TABLE_NAME;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------
-- 1. ORGANIZACIÓN
--    Líneas de mando y departamentos son estables (ids fijos del Excel).
--    Subdepartamentos sí pueden crecer: id autogenerado. Tras cargar el
--    seed con ids explícitos, ejecutar:
--      SELECT setval(pg_get_serial_sequence('subdepartamentos','id'),
--                    (SELECT max(id) FROM subdepartamentos));
-- ---------------------------------------------------------------------

CREATE TABLE lineas_mando (
  id                  integer PRIMARY KEY,
  nombre              text NOT NULL UNIQUE,
  activa              boolean NOT NULL DEFAULT true,
  creado_en           timestamptz NOT NULL DEFAULT now(),
  creado_por          integer,
  actualizado_en      timestamptz NOT NULL DEFAULT now(),
  actualizado_por     integer
);

CREATE TABLE departamentos (
  id                  integer PRIMARY KEY,
  linea_mando_id      integer NOT NULL REFERENCES lineas_mando(id),
  nombre              text NOT NULL UNIQUE,
