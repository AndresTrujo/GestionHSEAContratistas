  -- foto de autorización
  empleado_rol_id         bigint REFERENCES empleado_roles(id),
  cargo_area_id           bigint REFERENCES cargos_area(id),
  credencial_firma_id     bigint REFERENCES credenciales_firma(id), -- PIN verificado; NULL si no se exige PIN
  nombre_firmante         text NOT NULL,
  puesto_firmante         text NOT NULL,
  firmado_en              timestamptz NOT NULL DEFAULT now(),
  hash_documento          text,                       -- sha256 del contenido firmado
  -- trazo manuscrito como data URL PNG (máx. ~300 KB); NULL si no se dibujó
  imagen_firma            text CHECK (imagen_firma IS NULL
                                      OR (imagen_firma LIKE 'data:image/png;base64,%' AND length(imagen_firma) <= 300100)),
  CHECK ((firmante_tipo = 'EMPLEADO'          AND no_empleado IS NOT NULL AND usuario_proveedor_id IS NULL)
      OR (firmante_tipo = 'USUARIO_PROVEEDOR' AND usuario_proveedor_id IS NOT NULL AND no_empleado IS NULL)),
  -- un solo firmante por rol en cada permiso
  UNIQUE (permiso_id, rol_firma)
